#!/usr/bin/env python3
"""Independent CPython binary64 parse corpus. Deterministic, no network.
The numeric port does NOT call Python or host strtod in native execution.
"""
from pathlib import Path
import random,struct,math
out=Path(__file__).resolve().parents[1]/'tests/dtoa_vectors.h'
known=['0','-0','0.1','1.00000000000000011102230246251565404236316680908203125','1.00000000000000011102230246251565404236316680908203126','2.2250738585072014e-308','2.2250738585072011e-308','4.9406564584124654e-324','2.4703282292062327e-324','1.7976931348623157e308','9007199254740993','-9007199254740993','1e309','-1e309','1e-999']
r=random.Random(0x103d70a);pairs=[]
for text in known:
 bits=struct.unpack('<Q',struct.pack('<d',float(text)))[0];pairs.append((text,bits))
while len(pairs)<1040:
 bits=r.getrandbits(64);value=struct.unpack('<d',struct.pack('<Q',bits))[0]
 if not math.isfinite(value):continue
 text=repr(value);assert struct.unpack('<Q',struct.pack('<d',float(text)))[0]==bits;pairs.append((text,bits))
s='/* Generated by generate-dtoa-vectors.py: CPython independently parsed binary64. */\nstatic const struct {const char*text;uint64_t bits;} dtoa_vectors[]={\n'
for text,bits in pairs:s+=' {"'+text+'",UINT64_C(0x%016x)},\n'%bits
out.write_text(s+'};\n')
print('Generated',len(pairs),'independent numeric parse vectors')
